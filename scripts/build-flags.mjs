// One-off generator (dev-time only; nothing here ships in the JS bundle):
//   node scripts/build-flags.mjs
//
// 1. Writes src/lib/forms/country-table.ts: every country with a flag, its
//    English name and calling code (libphonenumber-js metadata + Intl.DisplayNames).
// 2. Copies the flag SVGs for those countries (plus EU) from country-flag-icons
//    into public/flags/<iso>.svg, minified with svgo. They are served as
//    static, CDN-cached files and loaded lazily by <Flag />.
import { mkdirSync, readFileSync, readdirSync, writeFileSync, rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { getCountries, getCountryCallingCode } from 'libphonenumber-js/min'
import { optimize } from 'svgo'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const flagSrc = join(root, 'node_modules/country-flag-icons/3x2')
const flagOut = join(root, 'public/flags')
const available = new Set(readdirSync(flagSrc).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)))

const names = new Intl.DisplayNames(['en'], { type: 'region' })
const rows = getCountries()
  .filter((iso) => available.has(iso))
  .map((iso) => ({ iso, name: names.of(iso) ?? iso, cc: getCountryCallingCode(iso) }))
  .sort((a, b) => a.name.localeCompare(b.name, 'en'))

const body = rows.map((r) => `  [${JSON.stringify(r.iso)}, ${JSON.stringify(r.name)}, ${JSON.stringify(r.cc)}],`).join('\n')
writeFileSync(
  join(root, 'src/lib/forms/country-table.ts'),
  `// GENERATED by scripts/build-flags.mjs. Do not edit by hand.\n// [ISO 3166-1 alpha-2, English name, calling code]\nexport const COUNTRY_TABLE: ReadonlyArray<readonly [string, string, string]> = [\n${body}\n]\n`,
)

rmSync(flagOut, { recursive: true, force: true })
mkdirSync(flagOut, { recursive: true })
let total = 0
for (const iso of new Set([...rows.map((r) => r.iso), 'EU'])) {
  if (!available.has(iso)) continue
  const svg = optimize(readFileSync(join(flagSrc, `${iso}.svg`), 'utf8'), { multipass: true, floatPrecision: 1 }).data
  writeFileSync(join(flagOut, `${iso.toLowerCase()}.svg`), svg)
  total += Buffer.byteLength(svg)
}
console.log(`${rows.length} countries; flags: ${readdirSync(flagOut).length} files, ${(total / 1024).toFixed(0)} KB total, ${(total / readdirSync(flagOut).length).toFixed(0)} B avg`)
