import { COUNTRY_TABLE } from './country-table'

// Default-country handling for the form phone field: Nigerian visitors type
// 0803..., so a form needs to know which calling code to put in front.

export interface Country {
  iso: string
  name: string
  cc: string
}

/** Markets shown first in the picker (and the order callingCode() falls back on). */
const POPULAR = ['NG', 'GH', 'KE', 'ZA', 'UG', 'TZ', 'EG', 'SN', 'CI', 'CM', 'GB', 'US', 'CA', 'IN', 'AE', 'SA', 'BR', 'PT', 'ES', 'MX', 'FR', 'DE', 'KR', 'PH', 'ID', 'PK', 'BD']

const ALL: Country[] = COUNTRY_TABLE.map(([iso, name, cc]) => ({ iso, name, cc }))
const byIso = new Map(ALL.map((c) => [c.iso, c]))

/** Every country with a flag (generated by scripts/build-flags.mjs), common markets first, then A-Z. */
export const COUNTRIES: Country[] = [
  ...POPULAR.map((iso) => byIso.get(iso)).filter((c): c is Country => !!c),
  ...ALL.filter((c) => !POPULAR.includes(c.iso)),
]
export const POPULAR_COUNT = POPULAR.length

export function findCountry(iso: string | undefined | null): Country | undefined {
  return byIso.get((iso ?? '').toUpperCase())
}

/** Calling codes shared by several countries resolve to their main market. */
const SHARED_CODE_HOME: Record<string, string> = { '1': 'US', '7': 'RU', '44': 'GB', '212': 'MA', '358': 'FI', '599': 'CW', '262': 'RE', '590': 'GP', '47': 'NO', '61': 'AU', '64': 'NZ' }

/**
 * Split a stored "+2348031234567" into its country and national part, using the
 * longest matching calling code (so +1 242 is not read as +1 + 242...). Returns
 * null when it has no leading "+" or no known code. Shared codes (+1, +44, +7)
 * resolve to the most common market.
 */
export function splitInternational(phone: string | null | undefined): { iso: string; national: string } | null {
  const digits = (phone ?? '').trim().replace(/[\s().-]/g, '')
  if (!digits.startsWith('+')) return null
  const d = digits.slice(1)
  if (!/^\d+$/.test(d)) return null
  for (let len = 3; len >= 1; len--) {
    const cc = d.slice(0, len)
    const match = COUNTRIES.find((c) => c.cc === cc && (SHARED_CODE_HOME[cc] ?? c.iso) === c.iso)
    if (match) return { iso: match.iso, national: d.slice(len) }
  }
  return null
}

export const DEFAULT_COUNTRY = 'NG'

export function callingCode(iso: string | undefined | null): string {
  const c = COUNTRIES.find((x) => x.iso === (iso ?? '').toUpperCase())
  return (c ?? COUNTRIES[0]).cc
}

/**
 * Turn what a visitor typed into "+<digits>" ready for the contact upsert, or
 * null when it cannot be a phone number.
 *
 *  +2348031234567   -> +2348031234567
 *  002348031234567  -> +2348031234567
 *  08031234567      -> +2348031234567   (national, trunk 0 dropped, default country)
 *  2348031234567    -> +2348031234567   (already starts with the calling code)
 */
export function normalizeFormPhone(raw: unknown, defaultIso?: string | null): string | null {
  if (typeof raw !== 'string') return null
  let s = raw.trim().replace(/[\s().-]/g, '')
  if (!s) return null
  let digits: string
  if (s.startsWith('+')) {
    digits = s.slice(1)
  } else if (s.startsWith('00')) {
    digits = s.slice(2)
  } else {
    const cc = callingCode(defaultIso)
    const d = s
    if (!/^\d+$/.test(d)) return null
    if (d.startsWith(cc) && d.length >= cc.length + 8) digits = d
    else digits = cc + d.replace(/^0+/, '')
  }
  s = digits
  if (!/^\d+$/.test(s)) return null
  // E.164: at most 15 digits; at least a country code plus a few digits.
  if (s.length < 8 || s.length > 15) return null
  return '+' + s
}

/** Client-side: what the visitor typed + the country picked, as +digits (or the raw text if it cannot be one). */
export function composeFormPhone(raw: unknown, iso: string): string {
  return normalizeFormPhone(raw, iso) ?? String(raw ?? '').trim()
}

/** Country the picker starts on: the fixed one, or the visitor's (Cloudflare), or Nigeria. */
export function resolveDefaultCountry(setting: string | undefined | null, detected: string | undefined | null): string {
  const known = (iso?: string | null) => (iso && COUNTRIES.some((c) => c.iso === iso.toUpperCase()) ? iso.toUpperCase() : null)
  if (!setting || setting === 'auto') return known(detected) ?? DEFAULT_COUNTRY
  return known(setting) ?? DEFAULT_COUNTRY
}
